<?php

namespace Tests\Feature;

use App\Models\Farm;
use App\Models\FarmModule;
use App\Models\Lot;
use App\Models\Module;
use App\Models\Potrero;
use App\Models\Species;
use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\Schema;
use Tests\TestCase;

/**
 * Fase 1 del módulo Potreros: identificación y características físicas
 * (código interno, superficie, capacidad UA, estado operativo, pastura,
 * topografía, cercado, fuentes de agua y notas) sin romper la lógica de
 * cupos existente.
 */
class PotrerosManagementTest extends TestCase
{
    use RefreshDatabase;

    private function bootstrap(string $key): array
    {
        $this->artisan('app:init-root');

        $farm = Farm::create(['name' => "Granja {$key}", 'sector' => 'bovino', 'is_active' => true]);

        $module = Module::where('code', 'potreros')->first();
        if ($module) {
            FarmModule::where('farm_id', $farm->id)
                ->where('module_id', $module->id)
                ->update(['is_enabled' => true]);
        }

        $admin = User::create([
            'farm_id' => $farm->id,
            'name' => "Admin {$key}",
            'email' => "admin_{$key}@test.com",
            'password_hash' => Hash::make('password123'),
            'role' => 'admin',
            'is_active' => true,
        ]);

        $species = Species::create([
            'farm_id' => $farm->id,
            'name' => "Bovino {$key}",
            'category' => 'bovina',
            'is_active' => true,
        ]);

        $token = $this->postJson('/api/v1/auth/login', [
            'email' => $admin->email,
            'password' => 'password123',
        ])->json('data.access_token');

        return [$farm, $token, $species];
    }

    public function test_potreros_table_has_management_columns(): void
    {
        foreach ([
            'code',
            'superficie_ha',
            'capacidad_ua',
            'operational_status',
            'tipo_pastura',
            'topografia',
            'tipo_cercado',
            'fuente_agua',
            'notes',
        ] as $column) {
            $this->assertTrue(
                Schema::hasColumn('potreros', $column),
                "Column '{$column}' is missing from 'potreros' table."
            );
        }
    }

    public function test_admin_can_create_potrero_with_management_fields_and_autogenerated_code(): void
    {
        [$farm, $token, $species] = $this->bootstrap('create');

        $res = $this->withHeaders(['Authorization' => 'Bearer '.$token])->postJson('/api/v1/potreros', [
            'name' => 'Potrero El Jobo',
            'species_id' => $species->id,
            'purpose' => 'Carne',
            'max_capacity' => 120,
            'superficie_ha' => 14.5,
            'capacidad_ua' => 18.75,
            'operational_status' => 'descanso',
            'tipo_pastura' => 'Brachiaria brizantha',
            'topografia' => 'ondulado',
            'tipo_cercado' => 'Cerca eléctrica',
            'fuente_agua' => ['Bebedero automático', 'Jagüey / Estanque', 'Bebedero automático'],
            'notes' => 'Suelo con pendiente leve.',
        ]);

        $res->assertStatus(201);
        $this->assertMatchesRegularExpression('/^POT-\d{4}$/', (string) $res->json('data.code'));
        $this->assertSame('POT-0001', $res->json('data.code'));
        $this->assertSame('14.50', (string) $res->json('data.superficie_ha'));
        $this->assertSame('18.75', (string) $res->json('data.capacidad_ua'));
        $this->assertSame('descanso', $res->json('data.operational_status'));
        $this->assertSame('Brachiaria brizantha', $res->json('data.tipo_pastura'));
        $this->assertSame('ondulado', $res->json('data.topografia'));
        $this->assertSame('Cerca eléctrica', $res->json('data.tipo_cercado'));
        // Fuentes de agua deduplicadas.
        $this->assertSame(['Bebedero automático', 'Jagüey / Estanque'], $res->json('data.fuente_agua'));
        $this->assertSame('Suelo con pendiente leve.', $res->json('data.notes'));

        $this->assertDatabaseHas('potreros', [
            'farm_id' => $farm->id,
            'code' => 'POT-0001',
            'operational_status' => 'descanso',
        ]);
    }

    public function test_operational_status_defaults_to_disponible_and_fields_are_optional(): void
    {
        [, $token, $species] = $this->bootstrap('defaults');

        $res = $this->withHeaders(['Authorization' => 'Bearer '.$token])->postJson('/api/v1/potreros', [
            'name' => 'Potrero Simple',
            'species_id' => $species->id,
            'purpose' => 'Carne',
            'max_capacity' => 50,
        ]);

        $res->assertStatus(201);
        $this->assertSame('disponible', $res->json('data.operational_status'));
        $this->assertNull($res->json('data.superficie_ha'));
        $this->assertNull($res->json('data.capacidad_ua'));
        $this->assertNull($res->json('data.fuente_agua'));
    }

    public function test_potrero_code_is_sequential_per_farm_and_explicit_duplicates_are_rejected(): void
    {
        [, $token, $species] = $this->bootstrap('codes');
        $auth = ['Authorization' => 'Bearer '.$token];

        $base = [
            'species_id' => $species->id,
            'purpose' => 'Carne',
            'max_capacity' => 40,
        ];

        $first = $this->withHeaders($auth)->postJson('/api/v1/potreros', $base + ['name' => 'P1'])->assertStatus(201);
        $second = $this->withHeaders($auth)->postJson('/api/v1/potreros', $base + ['name' => 'P2'])->assertStatus(201);

        $this->assertSame('POT-0001', $first->json('data.code'));
        $this->assertSame('POT-0002', $second->json('data.code'));

        // Código explícito duplicado en la misma granja: rechazado.
        $this->withHeaders($auth)->postJson('/api/v1/potreros', $base + [
            'name' => 'P3',
            'code' => 'POT-0001',
        ])->assertStatus(422)->assertJsonValidationErrors(['code']);
    }

    public function test_potrero_code_is_isolated_across_farms(): void
    {
        [, $tokenA, $speciesA] = $this->bootstrap('farm_a');
        [, $tokenB, $speciesB] = $this->bootstrap('farm_b');

        $resA = $this->withHeaders(['Authorization' => 'Bearer '.$tokenA])->postJson('/api/v1/potreros', [
            'name' => 'Potrero A',
            'species_id' => $speciesA->id,
            'purpose' => 'Carne',
            'max_capacity' => 30,
        ])->assertStatus(201);

        $resB = $this->withHeaders(['Authorization' => 'Bearer '.$tokenB])->postJson('/api/v1/potreros', [
            'name' => 'Potrero B',
            'species_id' => $speciesB->id,
            'purpose' => 'Carne',
            'max_capacity' => 30,
        ])->assertStatus(201);

        $this->assertSame('POT-0001', $resA->json('data.code'));
        $this->assertSame('POT-0001', $resB->json('data.code'));
    }

    public function test_potrero_rejects_invalid_enums_and_negative_numbers(): void
    {
        [, $token, $species] = $this->bootstrap('invalid');
        $auth = ['Authorization' => 'Bearer '.$token];

        $base = [
            'name' => 'Potrero Inválido',
            'species_id' => $species->id,
            'purpose' => 'Carne',
            'max_capacity' => 40,
        ];

        $this->withHeaders($auth)->postJson('/api/v1/potreros', $base + ['operational_status' => 'ocupado'])
            ->assertStatus(422)->assertJsonValidationErrors(['operational_status']);

        $this->withHeaders($auth)->postJson('/api/v1/potreros', $base + ['topografia' => 'montañoso'])
            ->assertStatus(422)->assertJsonValidationErrors(['topografia']);

        $this->withHeaders($auth)->postJson('/api/v1/potreros', $base + ['superficie_ha' => -3])
            ->assertStatus(422)->assertJsonValidationErrors(['superficie_ha']);

        $this->withHeaders($auth)->postJson('/api/v1/potreros', $base + ['capacidad_ua' => -1])
            ->assertStatus(422)->assertJsonValidationErrors(['capacidad_ua']);
    }

    public function test_admin_can_update_management_fields(): void
    {
        [, $token, $species] = $this->bootstrap('update');
        $auth = ['Authorization' => 'Bearer '.$token];

        $id = $this->withHeaders($auth)->postJson('/api/v1/potreros', [
            'name' => 'Potrero Update',
            'species_id' => $species->id,
            'purpose' => 'Carne',
            'max_capacity' => 40,
        ])->assertStatus(201)->json('data.id');

        $updated = $this->withHeaders($auth)->putJson('/api/v1/potreros/'.$id, [
            'superficie_ha' => 22.4,
            'capacidad_ua' => 30,
            'operational_status' => 'mantenimiento',
            'tipo_pastura' => 'Megathyrsus maximus',
            'topografia' => 'quebrado',
            'tipo_cercado' => 'Púa de 4 hilos',
            'fuente_agua' => ['Caño natural'],
            'notes' => 'Requiere resiembra.',
        ]);

        $updated->assertStatus(200);
        $this->assertSame('22.40', (string) $updated->json('data.superficie_ha'));
        $this->assertSame('30.00', (string) $updated->json('data.capacidad_ua'));
        $this->assertSame('mantenimiento', $updated->json('data.operational_status'));
        $this->assertSame('quebrado', $updated->json('data.topografia'));
        $this->assertSame(['Caño natural'], $updated->json('data.fuente_agua'));
        $this->assertSame('Requiere resiembra.', $updated->json('data.notes'));
    }

    public function test_index_exposes_derived_operational_state_and_ua_per_ha(): void
    {
        [$farm, $token, $species] = $this->bootstrap('derived');
        $auth = ['Authorization' => 'Bearer '.$token];

        $id = $this->withHeaders($auth)->postJson('/api/v1/potreros', [
            'name' => 'Potrero Derivado',
            'species_id' => $species->id,
            'purpose' => 'Carne',
            'max_capacity' => 100,
            'superficie_ha' => 10,
            'capacidad_ua' => 25,
            'operational_status' => 'descanso',
        ])->assertStatus(201)->json('data.id');

        // Sin lotes activos: el estado mostrado es el manual y UA/ha se calcula.
        $index = $this->withHeaders($auth)->getJson('/api/v1/potreros')->assertStatus(200);
        $row = collect($index->json('data'))->firstWhere('id', $id);
        $this->assertSame('descanso', $row['operational_state']);
        $this->assertSame(2.5, (float) $row['ua_per_ha']);

        // Con un lote activo, el estado derivado pasa a "ocupado".
        Lot::create([
            'farm_id' => $farm->id,
            'potrero_id' => $id,
            'code' => 'LOT-00001',
            'species_id' => $species->id,
            'sector' => 'bovina',
            'purpose' => 'Carne',
            'quantity' => 10,
            'status' => Lot::STATUS_ACTIVE,
        ]);

        $index2 = $this->withHeaders($auth)->getJson('/api/v1/potreros')->assertStatus(200);
        $row2 = collect($index2->json('data'))->firstWhere('id', $id);
        $this->assertSame('ocupado', $row2['operational_state']);
    }
}
